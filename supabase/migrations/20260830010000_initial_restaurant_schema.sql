-- TGuia Food - schema inicial Supabase
-- Banco principal: PostgreSQL / Supabase

create extension if not exists pgcrypto;

create type public.order_status as enum (
  'open',
  'closing',
  'closed',
  'cancelled'
);

create type public.order_type as enum (
  'table',
  'counter',
  'cashier',
  'delivery'
);

create type public.member_role as enum (
  'owner',
  'admin',
  'cashier',
  'waiter',
  'kitchen'
);

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  service_rate numeric(5,2) not null default 10.00 check (service_rate >= 0 and service_rate <= 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.organization_members (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.member_role not null default 'waiter',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create table public.restaurant_tables (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  number integer not null check (number > 0),
  name text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, number)
);

create table public.product_categories (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  name text not null,
  display_order integer not null default 0,
  color text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, name)
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  category_id uuid references public.product_categories(id) on delete set null,
  code text,
  name text not null,
  sale_price numeric(12,2) not null default 0 check (sale_price >= 0),
  active boolean not null default true,
  kitchen_print boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, code)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  order_number bigint generated by default as identity,
  custom_code bigint,
  order_type public.order_type not null default 'table',
  table_id uuid references public.restaurant_tables(id) on delete set null,
  status public.order_status not null default 'open',
  customer_name text,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  opened_at timestamptz not null default now(),
  closing_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (order_type = 'table' and table_id is not null)
    or order_type <> 'table'
  )
);

create unique index orders_one_active_order_per_table
  on public.orders(table_id)
  where table_id is not null and status in ('open', 'closing');

create index orders_org_status_idx on public.orders(organization_id, status);
create index orders_table_idx on public.orders(table_id);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity numeric(12,3) not null default 1 check (quantity > 0),
  notes text,
  kitchen_printed_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index order_items_order_idx on public.order_items(order_id);

create table public.order_payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  method text not null,
  amount numeric(12,2) not null check (amount > 0),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index order_payments_order_idx on public.order_payments(order_id);

