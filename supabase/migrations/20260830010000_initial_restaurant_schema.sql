-- Totais calculados no banco para evitar divergencia no frontend.
create or replace view public.order_totals
with (security_invoker = true)
as
select
  o.id as order_id,
  o.organization_id,
  coalesce(sum(oi.unit_price * oi.quantity), 0)::numeric(12,2) as subtotal,
  round(
    coalesce(sum(oi.unit_price * oi.quantity), 0)
    * coalesce(org.service_rate, 0) / 100,
    2
  )::numeric(12,2) as service_amount,
  round(
    coalesce(sum(oi.unit_price * oi.quantity), 0)
    * (1 + coalesce(org.service_rate, 0) / 100),
    2
  )::numeric(12,2) as total
from public.orders o
join public.organizations org on org.id = o.organization_id
left join public.order_items oi on oi.order_id = o.id
group by o.id, o.organization_id, org.service_rate;
